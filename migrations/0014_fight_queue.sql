create table if not exists fight_queue (
  id text primary key,
  dojo_id text not null,
  student_id text not null,
  ready_at bigint not null,
  status text not null,
  match_id text,
  opponent_id text
);

create table if not exists fight_matches (
  id text primary key,
  dojo_id text not null,
  a_id text not null,
  b_id text not null,
  a_name text not null,
  b_name text not null,
  a_hp integer not null default 100,
  b_hp integer not null default 100,
  a_rounds integer not null default 0,
  b_rounds integer not null default 0,
  round_no integer not null default 1,
  match_no integer not null default 1,
  word text not null default '',
  a_typed text not null default '',
  b_typed text not null default '',
  last_word text not null default '',
  deadline bigint not null default 0,
  window_ms integer not null default 2400,
  phase text not null,
  until_at bigint not null default 0,
  banner text not null default '',
  last_blow text not null default '',
  a_pose text not null default 'idle',
  b_pose text not null default 'idle',
  pose_until bigint not null default 0,
  a_hits integer not null default 0,
  b_hits integer not null default 0,
  a_clean integer not null default 0,
  b_clean integer not null default 0,
  a_hurt integer not null default 0,
  b_hurt integer not null default 0,
  updated_at bigint not null
);
